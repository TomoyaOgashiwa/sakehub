async function readExistingCocktails() {
  const files = (await readdir(COCKTAILS_DIR)).filter((file) => file.endsWith('.json')).sort();
  const cocktails = [];

  for (const file of files) {
    const raw = JSON.parse(await readFile(path.join(COCKTAILS_DIR, file), 'utf8'));
    cocktails.push(raw);
  }

  return cocktails;
}

function formatCounts(counts) {
  return Object.keys(TARGETS)
    .map((baseSpirit) => `${baseSpirit}: ${counts.get(baseSpirit) ?? 0}`)
    .join(', ');
}

async function main() {
  const existingCocktails = await readExistingCocktails();
  const existingSlugs = new Set(existingCocktails.map((cocktailSeed) => cocktailSeed.slug));
  const counts = new Map(Object.keys(TARGETS).map((baseSpirit) => [baseSpirit, 0]));

  for (const cocktailSeed of existingCocktails) {
    if (counts.has(cocktailSeed.baseSpirit)) {
      counts.set(cocktailSeed.baseSpirit, counts.get(cocktailSeed.baseSpirit) + 1);
    }
  }

  const candidateSlugs = new Set();
  const written = [];
  const skipped = [];

  for (const cocktailSeed of PHASE1_COCKTAILS) {
    if (candidateSlugs.has(cocktailSeed.slug)) {
      throw new Error(`duplicate generator slug: ${cocktailSeed.slug}`);
    }
    candidateSlugs.add(cocktailSeed.slug);

    const target = TARGETS[cocktailSeed.baseSpirit];
    if (target == null) {
      throw new Error(`unexpected baseSpirit ${cocktailSeed.baseSpirit} for ${cocktailSeed.slug}`);
    }

    if (existingSlugs.has(cocktailSeed.slug)) {
      skipped.push(cocktailSeed.slug);
      continue;
    }

    const current = counts.get(cocktailSeed.baseSpirit) ?? 0;
    if (current >= target) {
      skipped.push(cocktailSeed.slug);
      continue;
    }

    if (!SLUG_PATTERN.test(cocktailSeed.slug)) {
      throw new Error(`invalid slug: ${cocktailSeed.slug}`);
    }
    const outPath = path.join(COCKTAILS_DIR, `${cocktailSeed.slug}.json`);
    if (path.dirname(path.resolve(outPath)) !== path.resolve(COCKTAILS_DIR)) {
      throw new Error(`path escape for slug: ${cocktailSeed.slug}`);
    }
    // Scaffold only: never overwrite existing JSON (data/cocktails is canonical).
    await writeFile(outPath, `${JSON.stringify(cocktailSeed, null, 2)}\n`, 'utf8');
    existingSlugs.add(cocktailSeed.slug);
    counts.set(cocktailSeed.baseSpirit, current + 1);
    written.push(cocktailSeed.slug);
  }

  const mismatches = Object.entries(TARGETS).filter(([baseSpirit, target]) => {
    return counts.get(baseSpirit) !== target;
  });

  if (mismatches.length > 0) {
    throw new Error(
      `Phase1 target mismatch: ${mismatches
        .map(([baseSpirit, target]) => `${baseSpirit}=${counts.get(baseSpirit) ?? 0}/${target}`)
        .join(', ')}`,
    );
  }

  await mkdir(path.join(ROOT, 'data'), { recursive: true });

  console.log(`Wrote ${written.length} cocktail file(s).`);
  if (skipped.length > 0) {
    console.log(`Skipped ${skipped.length} existing or over-target slug(s).`);
  }
  console.log(`Final counts: ${formatCounts(counts)}`);
}

main().catch((error) => {
  console.error(error);
  process.exit(1);
});
