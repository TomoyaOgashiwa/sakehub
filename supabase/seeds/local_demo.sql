-- ---------------------------------------------------------------------------
-- 6. cocktail_recipe_ratings
--    published の非公式レシピ × 全デモユーザー（自作レシピは除く）
--    rating は 3〜5 に偏らせ、一部ユーザーはコメント付き
-- ---------------------------------------------------------------------------
INSERT INTO cocktail_recipe_ratings (user_id, recipe_id, rating, comment)
SELECT
  u.id,
  cr.id,
  (3 + (abs(hashtext(u.id::text || cr.id::text)) % 3))::smallint AS rating,
  CASE abs(hashtext(cr.id::text || u.email)) % 5
    WHEN 0 THEN '自宅で再現しましたが、お店の味に近くて驚きました。'
    WHEN 1 THEN '材料の比率が絶妙で、とても飲みやすかったです。'
    WHEN 2 THEN '友人にも振る舞いましたが大好評でした。'
    WHEN 3 THEN 'シンプルな手順で作りやすいレシピです。'
    ELSE ''
  END AS comment
FROM auth.users u
CROSS JOIN cocktail_recipes cr
WHERE u.email LIKE 'rater%@example.com'
  AND cr.status = 'published'
  AND NOT cr.is_official
  AND cr.user_id <> u.id;

