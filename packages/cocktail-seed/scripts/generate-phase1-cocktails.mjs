function ingredient(name, amount, unit = 'ml') {
  return { name, amount, unit };
}

function stepsFor(method) {
  switch (method) {
    case 'stir':
      return [
        'ミキシンググラスに材料と氷を入れる。',
        'ステアしてしっかり冷やし、香味をなじませる。',
        '冷やしたグラスに注ぐ。',
      ];
    case 'build':
      return ['グラスに氷を入れる。', '材料を順に注ぐ。', '軽く混ぜて仕上げる。'];
    case 'blend':
      return [
        'ブレンダーに材料とクラッシュドアイスを入れる。',
        'なめらかになるまで攪拌する。',
        '冷やしたグラスに注ぐ。',
      ];
    case 'muddle':
      return [
        'グラスの中でフルーツやハーブを軽くつぶす。',
        '残りの材料と氷を加える。',
        'よく混ぜて仕上げる。',
      ];
    case 'heat':
      return [
        '耐熱グラスに甘味やスパイスを入れる。',
        '温めた材料を注ぐ。',
        '軽く混ぜて温かいうちに提供する。',
      ];
    case 'shake':
    default:
      return [
        'シェーカーに材料と氷を入れる。',
        'しっかりシェイクして冷やす。',
        '冷やしたグラスに注ぐ。',
      ];
  }
}

function cocktail({
  slug,
  name,
  nameEn,
  description,
  baseSpirit,
  abv,
  originCountry,
  aliases = [],
  ingredients,
  method = 'shake',
  memo,
  steps,
}) {
  return {
    slug,
    id: null,
    name,
    nameEn,
    description,
    baseSpirit,
    abv,
    originCountry,
    aliases,
    officialRecipe: {
      name: `${name}（基本レシピ）`,
      memo: memo ?? 'クラシックな配合を家庭でも作りやすい一杯分に整えた基本レシピ。',
      ingredients,
      steps: steps ?? stepsFor(method),
    },
  };
}

